#!/usr/bin/env python3
"""Generate the HEIF-probe test fixtures (tiny gradient images).

Fixtures (NOT product code; test data with recorded provenance):
  - fixtures/gradient.heic  — real HEVC payload, encoded via the
    pillow-heif wheel (x265, dev-machine only, never distributed);
  - fixtures/gradient.avif  — real AV1 payload, encoded via ffmpeg's
    libaom-av1 encoder (dev-machine only).

Both are data, not code. Product decoding goes through system libheif
(LGPL, dynamically linked) with decode-only plugins (libde265 for HEVC,
dav1d for AV1) — the probe proves that path.

The script refuses to write fixtures when the two payloads come out
identical (that bug produced a mislabeled .avif once — see the probe
session log): distinct sha256 per format is a hard precondition.

Requires on the dev machine: python env with pillow-heif; ffmpeg with
libaom-av1. In CI, the committed fixtures + provenance.json are
authoritative (this script re-generates byte-identical files only if
versions align; otherwise it reports a mismatch honestly).
Usage: python3 gen_fixtures.py [--out DIR]
"""

import argparse
import hashlib
import json
import platform
import shutil
import subprocess
import sys
from pathlib import Path

W, H = 64, 48  # small: fixture cost stays ~1-3 KB per format


def gradient_rgb(w: int, h: int) -> bytes:
    """Deterministic RGB gradient (same recipe family as the other spikes)."""
    out = bytearray()
    for y in range(h):
        for x in range(w):
            out += bytes(((x * 4) % 256, (y * 5) % 256, ((x + y) * 3) % 256))
    return bytes(out)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def ftyp_brand(data: bytes) -> str:
    """Return the major brand of the ftyp box (bytes 8..12), or '?'."""
    if len(data) < 12 or data[4:8] != b"ftyp":
        return "?"
    return data[8:12].decode("latin-1")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="fixtures", help="output directory")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    # ── source image as PNG (shared by both encoders) ──────────────────
    src = out / "gradient_src.png"
    try:
        import pillow_heif
        from PIL import Image

        raw = gradient_rgb(W, H)
        Image.frombytes("RGB", (W, H), raw).save(src, format="PNG")
        heif_generator = f"pillow-heif {pillow_heif.__version__} wheel (dev-only, never distributed)"
    except ImportError as e:
        print(f"SKIP (honest): pillow-heif unavailable in this env: {e}")
        print("The committed fixtures + provenance.json stay authoritative.")
        return 77  # distinct code: CI recognizes an honest skip

    # ── HEIC: real HEVC payload via the wheel's x265 ───────────────────
    heic_path = out / "gradient.heic"
    try:
        from PIL import Image  # noqa: F401 (already imported above)

        pillow_heif.register_heif_opener()
        with Image.open(src) as im:
            im.save(heic_path, format="HEIF", quality=60)
    except Exception as e:  # noqa: BLE001 — report and fail honestly
        print(f"FAIL: HEIC generation failed: {e}")
        return 1

    # ── AVIF: real AV1 payload via ffmpeg/libaom-av1 ────────────────────
    avif_path = out / "gradient.avif"
    ffmpeg = shutil.which("ffmpeg")
    if ffmpeg is None:
        print("FAIL: ffmpeg not found on PATH (needed for the AVIF fixture)")
        return 1
    av1 = subprocess.run(
        [ffmpeg, "-hide_banner", "-loglevel", "error", "-y",
         "-i", str(src), "-c:v", "libaom-av1", "-frames:v", "1",
         "-f", "avif", str(avif_path)],
        check=False, capture_output=True, text=True,
    )
    if av1.returncode != 0 or not avif_path.exists():
        print(f"FAIL: ffmpeg libaom-av1 encode failed: {av1.stderr[-400:]}")
        return 1

    # ── hard precondition: distinct, correctly-branded payloads ────────
    heic_b = heic_path.read_bytes()
    avif_b = avif_path.read_bytes()
    heic_sha, avif_sha = sha256(heic_b), sha256(avif_b)
    heic_brand, avif_brand = ftyp_brand(heic_b), ftyp_brand(avif_b)
    problems = []
    if heic_sha == avif_sha:
        problems.append("HEIC and AVIF payloads are identical (mislabeled fixture bug)")
    if not heic_brand.startswith("heic"):
        problems.append(f"HEIC fixture brand is {heic_brand!r}, expected heic*")
    if avif_brand != "avif":
        problems.append(f"AVIF fixture brand is {avif_brand!r}, expected avif")
    if problems:
        for p in problems:
            print(f"FAIL: {p}")
        return 1

    files = {
        str(heic_path): {
            "origin": "generated by tools/gen_fixtures.py (this project)",
            "generator": heif_generator,
            "encoder_payload": "HEVC via x265 (wheel-bundled, dev-only)",
            "python": platform.python_version(),
            "size_bytes": len(heic_b),
            "sha256": heic_sha,
            "ftyp_brand": heic_brand,
            "pixels": f"{W}x{H} RGB gradient (deterministic recipe in gen_fixtures.py)",
        },
        str(avif_path): {
            "origin": "generated by tools/gen_fixtures.py (this project)",
            "generator": f"ffmpeg {ffmpeg} (dev-only)",
            "encoder_payload": "AV1 via libaom-av1",
            "size_bytes": len(avif_b),
            "sha256": avif_sha,
            "ftyp_brand": avif_brand,
            "pixels": f"{W}x{H} RGB gradient (deterministic recipe in gen_fixtures.py)",
        },
    }
    for p, meta in files.items():
        print(f"wrote {p} ({meta['size_bytes']} bytes, brand={meta['ftyp_brand']}, sha256={meta['sha256'][:16]}...)")

    prov = {
        "generator_script": "tools/gen_fixtures.py",
        "note": "test data only; product decode path uses system libheif (LGPL, dynamic) with decode-only plugins (libde265 HEVC / dav1d AV1)",
        "files": files,
    }
    (out / "provenance.json").write_text(json.dumps(prov, indent=2) + "\n")
    print("provenance.json updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
