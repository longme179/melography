// ── randomized adversarial corpus (fixed seed → reproducible) ───────────────

#[test]
fn random_mutations_never_panic_and_never_misparse() {
    let base = identity_3d(4);
    let mut rng = XorShift(0x2026_1001_dead_beef);
    let mut parsed_ok = 0u32;
    let mut rejected = 0u32;
    for _ in 0..3000 {
        // Random byte-level mutation of a valid file.
        let mut bytes = base.clone().into_bytes();
        let n_mut = 1 + (rng.next() % 4) as usize;
        for _ in 0..n_mut {
            if bytes.is_empty() {
                break;
            }
            let pos = (rng.next() as usize) % bytes.len();
            match rng.next() % 4 {
                0 => bytes[pos] = b'x',  // garbage byte
                1 => bytes[pos] = b'\n', // break a token
                2 => {
                    bytes.remove(pos); // truncation
                }
                _ => bytes.insert(pos, b' '), // whitespace injection
            }
        }
        let mutated = String::from_utf8_lossy(&bytes).into_owned();
        match parse_cube(&mutated) {
            Ok(lut) => {
                // Whatever parsed must satisfy the invariants: finite
                // values, exact count, valid domain.
                assert!(lut.table.iter().all(|v| v.is_finite()));
                assert_eq!(lut.table.len() % 3, 0);
                for c in 0..3 {
                    assert!(lut.domain_min[c] < lut.domain_max[c]);
                }
                parsed_ok += 1;
            }
            Err(_) => rejected += 1,
        }
    }
    // The corpus must exercise both paths meaningfully (sanity, not a gate:
    // the property is "never panic + never violate invariants").
    assert!(
        parsed_ok > 100 && rejected > 100,
        "parsed={parsed_ok} rejected={rejected}"
    );
}

#[test]
fn fuzz_corpus_files() {
    // Every checked-in corpus file must produce a structured error (or a
    // valid parse if the file is a known-good control) — never a panic.
    let dir = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/fuzz_corpus");
    let mut checked = 0;
    if let Ok(entries) = std::fs::read_dir(dir) {
        for e in entries.flatten() {
            let path = e.path();
            if path.extension().and_then(|s| s.to_str()) != Some("cube") {
                continue;
            }
            let bytes = std::fs::read(&path).unwrap();
            let src = String::from_utf8_lossy(&bytes);
            // Either outcome is fine; panicking/hanging is not.
            let _ = parse_cube(&src);
            checked += 1;
        }
    }
    assert!(
        checked >= 8,
        "fuzz corpus missing (checked {checked} files)"
    );
}

#[test]
fn parser_is_deterministic_across_runs() {
    // Same input → same output structure (serde round-trip equal).
    let lut = parse_cube(identity_3d(3).as_str()).unwrap();
    let ser = serde_json::to_string(&lut).unwrap();
    let back: CubeLut = serde_json::from_str(&ser).unwrap();
    assert_eq!(lut, back);
}
